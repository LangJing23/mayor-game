/* ------------------------------------------------------------
 * 工具：行字符串 → 像素矩阵。'.' 与 '0' 均视为透明。
 * ------------------------------------------------------------ */
function fromRows(rows: string[], palette: string[]): Sprite {
  const h = rows.length;
  const w = rows[0].length;
  const pixels = rows.map((row) =>
    row.split('').map((ch) => (ch === '.' ? 0 : Number(ch))),
  );
  return { w, h, palette, pixels };
}

