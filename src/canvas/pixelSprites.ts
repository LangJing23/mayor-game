/**
 * 像素建筑精灵数据（原创）—— v2 视觉 refinement
 *
 * 设计依据 visual-style.md：
 * - 原创像素视觉，仅参考 Nitrome / 4399《高楼爆破》类游戏的"色块感、玩具感、清晰轮廓"气质，
 *   不复制任何具体素材、建筑造型或 UI。所有像素阵列为本项目手工编排。
 * - 建筑基础网格：tower 16×24、flat 16×16，绘制时按整数倍放大（见 drawSprite）。
 * - warning / halted 通过独立叠加层（overlay）表达；叠加层体积小、置于右上/侧面，
 *   不遮挡建筑主体，表达"这栋建筑处于某种状态"而非"盖了一个 UI icon"。
 *
 * refinement 要点（本轮）：
 * - tower 改为上下等宽的城市高层 silhouette（非锥形/火箭），顶部带设备层，垂直感强。
 * - flat 增加檐口 + 中央入口 + 立面层次，仍保持矮楼识别。
 * - construction / completed 的结构差异不依赖颜色：
 *     construction = 未封顶 + 裸露楼板 + 缺窗缺墙 + 脚手架；
 *     completed    = 完整屋顶 + 整齐窗 + 完成立面 + 高光 + flag。
 * - overlay 缩小且偏置；crane 增加桁架塔身与吊钩结构。
 *
 * 数据结构：Sprite = { w, h, palette, pixels }，pixels 索引 0 恒为透明。
 */

export interface Sprite {
  w: number;
  h: number;
  /** palette[0] 为透明占位，其余为颜色（#rrggbb） */
  palette: string[];
  /** h 行 × w 列的颜色索引矩阵 */
  pixels: number[][];
}

