/* ============================================================
 * 绘制工具（供 cityRenderer 与测试页共用）
 * ============================================================ */

/**
 * 将一个 Sprite 以指定放大倍数绘制到 Canvas。
 * @param ctx    2D 上下文
 * @param sprite 精灵
 * @param x,y    左上角起点（画布坐标）
 * @param scale  放大倍数（整数）
 */
export function drawSprite(
  ctx: CanvasRenderingContext2D,
  sprite: Sprite,
  x: number,
  y: number,
  scale: number,
): void {
  const { w, h, palette, pixels } = sprite;
  for (let row = 0; row < h; row++) {
    for (let col = 0; col < w; col++) {
      const idx = pixels[row][col];
      if (idx === 0) continue;
      const color = palette[idx];
      if (!color || color === 'transparent') continue;
      ctx.fillStyle = color;
      ctx.fillRect(x + col * scale, y + row * scale, scale, scale);
    }
  }
}

/**
 * 非等比绘制：水平用 scaleX、垂直用 scaleY，各像素格可拉伸为矩形。
 * 用于塔吊这类需要"细高竖塔"的元素（塔身拉高、不过度加宽），不修改 sprite 数据本身。
 */
export function drawSpriteStretch(
  ctx: CanvasRenderingContext2D,
  sprite: Sprite,
  x: number,
  y: number,
  scaleX: number,
  scaleY: number,
): void {
  const { w, h, palette, pixels } = sprite;
  for (let row = 0; row < h; row++) {
    for (let col = 0; col < w; col++) {
      const idx = pixels[row][col];
      if (idx === 0) continue;
      const color = palette[idx];
      if (!color || color === 'transparent') continue;
      ctx.fillStyle = color;
      ctx.fillRect(
        Math.round(x + col * scaleX),
        Math.round(y + row * scaleY),
        Math.ceil(scaleX),
        Math.ceil(scaleY),
      );
    }
  }
}
